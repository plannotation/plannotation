class TestParsingIsBoundedToo:
    """The byte cap bounds a label's size; these bound what parsing it costs.

    A label can sit well inside :data:`_MAX_LABEL_BYTES` and still be expensive, and
    the document chooses how. SPEC 4.3 (7) bounds the resources a reader spends, not
    merely the bytes it reads, and SPEC 4.3 (2) requires anything that fails to read
    as absent rather than escaping.
    """

    @staticmethod
    def _deeply_nested(depth: int = 200_000) -> bytes:
        """Return a document whose page label is legal JSON nested far too deeply.

        Args:
            depth: How many array openings to nest.

        Returns:
            The document's bytes.
        """
        payload = b'{"planlabel":"0.1","x":' + b"[" * depth + b"]" * depth + b"}"
        return fx.build_filtered_label(payload)

    def test_a_label_that_nests_too_deeply_is_refused_and_not_a_recursion_error(
        self, tmp_path: Path
    ) -> None:
        """RecursionError is not a PlanLabelError, so unconverted it escapes read()."""
        source = write_bytes(tmp_path / "deep.pdf", self._deeply_nested())
        with pytest.raises(InvalidLabelError, match="nests too deeply"):
            embed.read(source)

    def test_such_a_label_reads_as_absent_when_lenient(self, tmp_path: Path) -> None:
        """SPEC 4.3 (2): a label that fails to read is absent, not an exception."""
        source = write_bytes(tmp_path / "deep.pdf", self._deeply_nested())
        assert embed.read(source, strict=False).pages == {}

    def test_the_refusal_is_cheap(self, tmp_path: Path) -> None:
        """The scanner raises before the payload is consumed, so this must be fast."""
        source = write_bytes(tmp_path / "deep.pdf", self._deeply_nested())
        started = time.perf_counter()
        with pytest.raises(InvalidLabelError):
            embed.read(source)
        assert time.perf_counter() - started < 1.0

    @staticmethod
    def _many_violations(count: int = 20_000) -> bytes:
        """Return a document whose page label breaks one rule many thousands of times.

        Args:
            count: How many invalid elements to write.

        Returns:
            The document's bytes.
        """
        document = {
            "planlabel": SCHEMA_VERSION,
            "provenance": "authored",
            "page": {"index": 0, "widthMm": 420, "heightMm": 297},
            "sheet": {"id": "A-101"},
            "elements": [
                {"id": f"e{n}", "ifcClass": "not-an-ifc-class", "paperBBox": [0, 0, 1, 1]}
                for n in range(count)
            ],
        }
        return fx.build_filtered_label(json.dumps(document).encode())

    def test_many_violations_cost_little_to_refuse(self, tmp_path: Path) -> None:
        """Only the reported errors are taken, so the refusal does not scale with them.

        Materialising and sorting every violation made the refusal cost more than the
        validation that produced it, and the count is the document's to choose.
        """
        source = write_bytes(tmp_path / "many.pdf", self._many_violations())
        started = time.perf_counter()
        with pytest.raises(InvalidLabelError) as caught:
            embed.read(source)
        assert time.perf_counter() - started < 0.5
        # The signature of taking only what is reported: the total is never counted,
        # so the message cannot name it. A reader that materialised every violation
        # would say "and 19995 more" here.
        assert str(caught.value).endswith("... and more")

    def test_the_refusal_message_is_bounded(self, tmp_path: Path) -> None:
        """A refusal is what "treat as absent" invites a caller to log."""
        source = write_bytes(tmp_path / "many.pdf", self._many_violations())
        with pytest.raises(InvalidLabelError) as caught:
            embed.read(source)
        assert len(str(caught.value)) < 4000

    @pytest.mark.parametrize("length", [0, 199, 200, 201, 5000])
    def test_a_quoted_fragment_is_clipped(self, length: int) -> None:
        """Everything quoted in a message came from the document being refused."""
        clipped = embed._clip("y" * length)
        assert len(clipped) <= 200 + len("... (+4800 characters)")
        assert clipped.startswith("y" * min(length, 200))

    def test_stripping_does_not_scale_quadratically_in_the_attachment_count(
        self, tmp_path: Path
    ) -> None:
        """Resolving each key against the name tree again would be O(n^2) in n.

        The number of attachments is the document's to choose, so a per-key lookup
        inside a walk of the same tree is an unbounded cost from a small file.
        """
        source = write_bytes(tmp_path / "many-files.pdf", fx.build_many_attachments(2500))
        started = time.perf_counter()
        embed.strip(source, tmp_path / "stripped.pdf")
        # Measured at 0.16 s walking the tree once, against about 2.3 s resolving each
        # key against it again. The budget sits between them with room on both sides.
        assert time.perf_counter() - started < 1.0
