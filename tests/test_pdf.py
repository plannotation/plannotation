#: The timestamp every call to :func:`planlabel.pdf.embed.attach` here injects. Nothing
#: in this module may read the clock, or the determinism tests would be testing it.
MOD_DATE: Final = datetime(2024, 1, 1, 12, 0, 0, tzinfo=UTC)

#: The PDF date string that timestamp becomes.
MOD_DATE_STRING: Final = "D:20240101120000Z"

#: The resolution the appearance guarantee is asserted at.
DPI: Final = 150.0

#: The design brief's ceiling on a committed fixture. Nothing here is committed, but a
#: fixture that outgrew it would be one nobody wants to regenerate.
FIXTURE_SIZE_LIMIT: Final = 200 * 1024

#: The eight values ISO 32000-2 allows in ``/AFRelationship``. A vendor value fails
#: PDF/A validation, and an omitted argument silently writes ``/Unspecified``.
AF_RELATIONSHIPS: Final = frozenset(
    {
        "/Source",
        "/Data",
        "/Alternative",
        "/Supplement",
        "/EncryptedPayload",
        "/FormData",
        "/Schema",
        "/Unspecified",
    }
)

#: Expected render shapes at 150 dpi: A3 landscape, and A4 portrait turned by
#: ``/Rotate 90`` and therefore *displayed* landscape.
A3_LANDSCAPE_SHAPE: Final = (1754, 2481, 3)
A4_DISPLAYED_LANDSCAPE_SHAPE: Final = (1241, 1754, 3)

#: Point displacements the appearance comparison must catch, largest first. The
#: smallest is a fiftieth of a pixel at 150 dpi.
NUDGES: Final = [1.0, 0.24, 0.1, 0.01]

#: The pixel floor the smallest displacement must still clear.
MIN_DIFFERING_PIXELS: Final = 1000

#: How long two runs must be apart before a clock-seeded value is bound to differ.
#:
#: This is the number that makes the determinism tests real. pikepdf's default ``/ID``
#: is seeded from the clock at one-second granularity: measured on this machine, two
#: saves inside the same second produce byte-identical files with ``deterministic_id``
#: switched off, and two saves 1.1 s apart do not. A determinism test that did not wait
#: would therefore pass with the flag removed -- which is exactly the bug it exists to
#: catch, and which is why the two tests that use this are marked slow rather than made
#: fast.
CLOCK_TICK: Final = 1.1

#: The foreign PDF Declaration the fixture carries, as it appears in the packet.
FOREIGN_DECLARATION: Final = f"<pdfd:conformsTo>{fx.FOREIGN_SPEC_URI}</pdfd:conformsTo>".encode()

#: Environment variables the veraPDF integration honours.
VERAPDF_BINARY_ENV: Final = "PLANLABEL_VERAPDF"
REQUIRE_EXTERNAL_ENV: Final = "PLANLABEL_REQUIRE_EXTERNAL"

#: How long veraPDF may take before the test gives up on it, in seconds.
VERAPDF_TIMEOUT: Final = 300.0

#: The three files a fully labelled two-page document carries.
LABEL_FILENAMES: Final = ("planlabel-p0000.json", "planlabel-p0001.json", INDEX_FILENAME)

#: Every file a labelled copy of the fixture carries, sorted as the name tree lists them.
ALL_FILENAMES: Final = sorted([*LABEL_FILENAMES, fx.FOREIGN_DOC_FILENAME, fx.FOREIGN_PAGE_FILENAME])


