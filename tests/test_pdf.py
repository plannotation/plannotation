def write_bytes(path: Path, data: bytes) -> Path:
    """Write bytes to a path and return it.

    Args:
        path: Where to write.
        data: What to write.

    Returns:
        ``path``, so that a fixture can build and name a file in one expression.
    """
    path.write_bytes(data)
    return path


def label(
    source: Path,
    target: Path,
    labels: list[PageLabel],
    index: LabelIndex | None,
    *,
    break_signature: bool = False,
    compress_labels: bool = True,
) -> embed.AttachReport:
    """Attach labels with this module's fixed timestamp.

    Args:
        source: The document to label.
        target: Where to write the labelled copy.
        labels: The page labels.
        index: The document-level index, or None to embed none.
        break_signature: Proceed although the document is signed.
        compress_labels: Store the embedded JSON Flate-encoded.

    Returns:
        The attach report.
    """
    return embed.attach(
        source,
        labels,
        index,
        target,
        mod_date=MOD_DATE,
        break_signature=break_signature,
        compress_labels=compress_labels,
    )


def attachment_names(pdf: Pdf) -> list[str]:
    """List the ``EmbeddedFiles`` name-tree keys of a document.

    Args:
        pdf: An open document.

    Returns:
        Every attachment name, sorted.
    """
    return sorted(pdf.attachments)


def attachment_bytes(pdf: Pdf, name: str) -> bytes:
    """Return the decoded contents of one attachment.

    Args:
        pdf: An open document.
        name: The name-tree key.

    Returns:
        The embedded file's bytes, decoded through whatever filter stores them.
    """
    return bytes(pdf.attachments[name].get_file().read_bytes())


def af_filenames(owner: Object) -> list[str]:
    """List the filenames an ``/AF`` array names, in array order.

    Args:
        owner: A page or catalog dictionary.

    Returns:
        The ``/UF`` of each entry, in order, with ``"<deleted>"`` for an entry whose
        file specification no longer resolves. Order matters: a foreign entry must keep
        its place and PlanLabel's must be appended after it.
    """
    entries = owner.get(Name.AF)
    if entries is None:
        return []
    return [
        "<deleted>" if entry is None else str(entry.get(Name.UF, entry.get(Name.F, "?")))
        for entry in (cast("Object | None", item) for item in entries)
    ]


def filespec_objects(pdf: Pdf) -> list[Object]:
    """Collect every ``/Type /Filespec`` object in a document.

    Args:
        pdf: An open document.

    Returns:
        The file specifications, as indirect objects. Counting these is how the tests
        show that registering a file in both the name tree and an ``/AF`` array shares
        one object rather than storing the file twice. Counting occurrences of the
        string in the file's bytes would not do: with object streams the dictionaries
        may be packed inside a stream.
    """
    return [
        obj
        for obj in pdf.objects
        if isinstance(obj, Dictionary) and obj.get(Name.Type) == Name.Filespec
    ]


def page_streams(path: Path) -> list[tuple[bytes, bytes]]:
    """Read every page's content stream, raw and decoded.

    Args:
        path: The document to read.

    Returns:
        One ``(raw, decoded)`` pair per page. The raw bytes are the assertion that
        matters: re-encoding a content stream changes them and changes no pixel at all,
        so the appearance comparison alone cannot police section 1.2 (1).
    """
    with pikepdf.open(path) as pdf:
        return [
            (
                bytes(page.obj[Name.Contents].read_raw_bytes()),
                bytes(page.obj[Name.Contents].read_bytes()),
            )
            for page in pdf.pages
        ]


def page_boxes(path: Path) -> list[tuple[str, str, str]]:
    """Read every page's boxes and rotation.

    Args:
        path: The document to read.

    Returns:
        One ``(mediabox, cropbox, rotate)`` triple per page, as text, so that a
        difference reads directly in a failure message.
    """
    with pikepdf.open(path) as pdf:
        return [
            (str(page.mediabox), str(page.cropbox), str(page.obj.get(Name.Rotate, 0)))
            for page in pdf.pages
        ]


def xmp_packet(path: Path) -> bytes | None:
    """Return a document's XMP packet.

    Args:
        path: The document to read.

    Returns:
        The catalog's ``/Metadata`` stream, decoded, or None when there is none.
    """
    with pikepdf.open(path) as pdf:
        metadata = pdf.Root.get(Name.Metadata)
        return None if metadata is None else bytes(metadata.read_bytes())


def docinfo(path: Path) -> dict[str, str]:
    """Return a document's information dictionary as plain strings.

    Args:
        path: The document to read.

    Returns:
        Every ``/Info`` entry as ``key -> value``.
    """
    with pikepdf.open(path) as pdf:
        return {str(key): str(value) for key, value in pdf.docinfo.items()}


def annotation_subtypes(path: Path, page_index: int) -> list[str]:
    """List the annotation subtypes on one page.

    Args:
        path: The document to read.
        page_index: The zero-based page.

    Returns:
        The ``/Subtype`` of each annotation, in order.
    """
    with pikepdf.open(path) as pdf:
        annots = pdf.pages[page_index].obj.get(Name.Annots)
        return [] if annots is None else [str(item.get(Name.Subtype)) for item in annots]


def difference_message(page_index: int, before: NDArray[np.uint8], after: NDArray[np.uint8]) -> str:
    """Describe how two renders of one page differ.

    Args:
        page_index: The zero-based page.
        before: The first render.
        after: The second.

    Returns:
        The library's own difference report, which names the page, counts the pixels
        and gives the bounding box in pixels and in points. Built only when an
        assertion has already failed, since ``assert`` evaluates its message lazily.
    """
    diff = render.diff_arrays(page_index, before, after, dpi=DPI)
    return "the arrays are equal" if diff is None else diff.describe()


