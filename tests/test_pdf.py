        """The document is opened read-only, whichever way this is called."""
        copy = write_bytes(tmp_path / "untouched.pdf", labelled.read_bytes())
        before = copy.read_bytes()
        embed.write_sidecar(copy)
        assert copy.read_bytes() == before

