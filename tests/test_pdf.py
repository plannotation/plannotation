class TestTheAppearanceTestCanFail:
    """A guarantee nobody has watched fail is a decoration.

    The twin differs by one number in one content stream, which moves one line of the
    building outline. Anti-aliasing is what gives exact comparison its sensitivity: at
    150 dpi a displacement of 0.01 pt is a fiftieth of a pixel, and it still moves
    thousands of pixels by a few levels.
    """

    @pytest.mark.parametrize("nudge", NUDGES)
    def test_a_displaced_line_is_caught(
        self, drawing_set: Path, tmp_path: Path, nudge: float
    ) -> None:
        """Moving one line by as little as a hundredth of a point changes the pixels."""
        twin = write_bytes(tmp_path / f"nudge-{nudge}.pdf", fx.build_drawing_set(nudge=nudge))
        before = render.render_page(drawing_set, 0, dpi=DPI)
        after = render.render_page(twin, 0, dpi=DPI)
        assert before.shape == after.shape
        assert not np.array_equal(before, after)

    @pytest.mark.parametrize("nudge", NUDGES)
    def test_the_assertion_fires_and_says_where(
        self, drawing_set: Path, tmp_path: Path, nudge: float
    ) -> None:
        """The carrier's assertion raises, naming the page it found the difference on."""
        twin = write_bytes(tmp_path / f"nudge-{nudge}.pdf", fx.build_drawing_set(nudge=nudge))
        with pytest.raises(AppearanceChangedError, match="page 0"):
            render.assert_same_appearance(drawing_set, twin, dpi=DPI)

    def test_only_the_changed_page_is_reported(self, drawing_set: Path, tmp_path: Path) -> None:
        """Page 1 is untouched by the nudge, and the report says so by omitting it."""
        twin = write_bytes(tmp_path / "nudge.pdf", fx.build_drawing_set(nudge=0.24))
        diffs = render.compare_documents(drawing_set, twin, dpi=DPI)
        assert [diff.page_index for diff in diffs] == [0]
        assert diffs[0].differing_pixels > 0
        assert diffs[0].max_channel_delta > 0
        assert diffs[0].bbox is not None

    def test_the_smallest_displacement_still_moves_thousands_of_pixels(
        self, drawing_set: Path, tmp_path: Path
    ) -> None:
        """A 0.01 pt move is a fiftieth of a pixel and is still unmistakable."""
        twin = write_bytes(tmp_path / "hair.pdf", fx.build_drawing_set(nudge=0.01))
        diffs = render.compare_documents(drawing_set, twin, dpi=DPI)
        assert diffs[0].differing_pixels > MIN_DIFFERING_PIXELS
        assert 0 < diffs[0].max_channel_delta < 255

    def test_a_changed_rotation_is_reported_as_a_changed_shape(
        self, drawing_set: Path, tmp_path: Path
    ) -> None:
        """Rewriting /Rotate changes the rendered size, which is its own failure mode."""
        twin = tmp_path / "unrotated.pdf"
        with pikepdf.open(drawing_set) as pdf:
            pdf.pages[1].obj[Name.Rotate] = 0
            embed.save_labelled(pdf, twin)
        diffs = render.compare_documents(drawing_set, twin, dpi=DPI)
        assert [diff.page_index for diff in diffs] == [1]
        assert diffs[0].shape_before != diffs[0].shape_after
        assert "rendered size changed" in diffs[0].describe()

    def test_a_dropped_annotation_is_caught_in_pixels(
        self, drawing_set: Path, tmp_path: Path
    ) -> None:
        """Annotations are part of how a page looks, so dropping one must be visible."""
