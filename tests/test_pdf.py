"""The Phase 2 gate: the PDF carrier, and the promise that a label is invisible.

The project's central claim is that a drawing can be labelled, and unlabelled, without
the drawing changing. This module holds that claim to account, and it is written so
that every assertion in it could fail.

The five gate items of the design brief's section 7
-------------------------------------------------
1. **The appearance guarantee.** Every page of the input and of the output is
   rasterised at 150 dpi with pdfium and the two ``numpy`` arrays are compared for
   exact equality -- no tolerance anywhere. :class:`TestTheAppearanceTestCanFail` then
   proves the comparison has teeth by moving one line by a hundredth of a point and
   watching it fire. A guarantee that has never been seen to fail is a decoration.
2. **Round trip.** ``read(attach(x)) == x`` for a two-page document, compared as
   canonical bytes rather than as models, because the bytes are what a third-party
   reader actually sees.
3. **Reader compatibility.** ``pikepdf.open().attachments`` finds every file. pdf.js's
   ``getAttachments()`` belongs to Phase 5, where the inspector arrives, and is
   deliberately not faked here; what *is* asserted is the structural fact that decides
   it, namely that every file PlanLabel writes is registered in the ``EmbeddedFiles``
   name tree and not only in an ``/AF`` array.
4. **veraPDF.** Run when it is installed and runnable, skipped otherwise, and never a
   reason for CI to fail. Detection runs ``verapdf --version``, because the CLI is a
   Java wrapper that can sit on ``PATH`` and still be unusable. Its report parser is
   unit-tested on every machine, so that it is not dead code on nearly all of them.
5. **The fixture**, generated by :mod:`tests.pdf_fixtures` with pikepdf alone -- not
   cairosvg, which needs a system libcairo that CI does not have.

Everything beyond the gate is here because the Phase 2 research showed it breaks: the
name tree is not automatic, ``/AF`` must be appended to and never assigned,
``/Params /CheckSum`` is computed once and never again, pikepdf's save defaults rewrite
metadata and content streams, and a signature cannot survive any save at all.

The classes after the gate items are regression tests. Each one names a defect that was
reproduced against this module and each was watched to fail before the fix that makes it
pass: a composed PDF Declaration, a conflict check that reads both registrations, a
bounded reader, the sidecar's index check, the PDF/A extension-schema risk, an emptied
name tree, a damaged ``/Metadata``, and refusing before writing rather than after.
"""

