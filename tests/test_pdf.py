# ---------------------------------------------------------------------------
# The parameters of a predictor are input too
# ---------------------------------------------------------------------------
#: How long undoing a predictor over a full-sized label may take, in seconds.
#:
#: Measured on this machine: the three array-shaped PNG filters undo fifteen mebibytes
#: in 6 ms, 90 ms and 15 ms, and inflating the zeros they are made of costs another
#: 50 ms or so. Before they were vectorised the same three cost 12 ms, 1.04 s and
#: 1.13 s, so this budget is several times what the reader now spends and comfortably
#: under what it used to.
PREDICTOR_TIME_BUDGET: Final = 0.75

#: The ``/DecodeParms`` of a byte-aligned PNG predictor over one eight-bit component.
PNG_PARMS: Final = Dictionary(Predictor=15, Colors=1, BitsPerComponent=8, Columns=512)


def predicted_zeros(tag: int, *, megabytes: int, columns: int = 512) -> bytes:
    """Build a document whose page-0 label inflates to tagged rows of zeros.

    Every PNG filter predicts zero from zeros, so a payload of zeros encodes to rows of
    zeros under all five filter types and the encoded form can be written directly
    rather than computed a byte at a time.

    Args:
        tag: The PNG filter type every row is tagged with.
        megabytes: How many mebibytes the label decodes to.
        columns: The decoded row length in bytes.

    Returns:
        The document's bytes.
    """
    rows = megabytes * 1024 * 1024 // columns
    encoded = (bytes([tag]) + bytes(columns)) * rows
    return fx.build_filtered_label(
        zlib.compress(encoded, 9),
        filters=Name.FlateDecode,
        decode_parms=Dictionary(Predictor=15, Colors=1, BitsPerComponent=8, Columns=columns),
    )


class TestPredictorParametersAreCheckedBeforeAnythingIsAllocated:
    """``/DecodeParms`` is three integers the document chooses (SPEC 4.3 (7), section 9).

    The row length was computed from ``/Columns``, ``/Colors`` and
    ``/BitsPerComponent`` and then allocated. A 1,317-byte document with ``/Columns
    2000000000`` cost 1,662 MB; a slightly larger one raised :class:`MemoryError`, which
    is not a :class:`~planlabel.errors.PlanLabelError`, so ``strict=False`` did not
    deliver the absence section 4.3 (2) promises and the CLI printed a traceback.
    """

    @staticmethod
    def with_parms(tmp_path: Path, name: str, parms: Dictionary) -> Path:
        """Write a document whose page-0 label declares one set of ``/DecodeParms``.

        Args:
            tmp_path: Where to write it.
            name: The filename to write it under.
            parms: The ``/DecodeParms`` dictionary.

        Returns:
            The document's path. Its stream inflates to nothing, which is the shape that
            used to slip past the check on the number of rows: zero bytes are a whole
            number of rows of every length.
        """
        return write_bytes(
            tmp_path / name,
            fx.build_filtered_label(
                zlib.compress(b"", 9), filters=Name.FlateDecode, decode_parms=parms
            ),
        )

    @pytest.mark.parametrize(
        ("parms", "named"),
        [
            (Dictionary(Predictor=12, Columns=2_000_000_000), "/Columns"),
            (Dictionary(Predictor=12, Columns=0), "/Columns"),
            (Dictionary(Predictor=12, Columns=-4), "/Columns"),
            (Dictionary(Predictor=12, Colors=0), "/Colors"),
            (Dictionary(Predictor=12, Colors=1_000_000), "/Colors"),
            (Dictionary(Predictor=12, BitsPerComponent=7), "/BitsPerComponent"),
            (Dictionary(Predictor=12, BitsPerComponent=1024), "/BitsPerComponent"),
            (Dictionary(Predictor=0), "/Predictor"),
            (Dictionary(Predictor=3), "/Predictor"),
            (Dictionary(Predictor=16), "/Predictor"),
            (Dictionary(Predictor=12, Columns=2.5), "/Columns"),
            (Dictionary(Predictor=12, Colors=Name.One), "/Colors"),
            (Dictionary(Predictor=Name.PNG), "/Predictor"),
        ],
    )
    def test_each_parameter_is_refused_by_name(
        self, tmp_path: Path, parms: Dictionary, named: str
    ) -> None:
        """The message names the parameter, because it is what nobody can see."""
        source = self.with_parms(tmp_path, "parms.pdf", parms)
        with pytest.raises(InvalidLabelError, match=re.escape(named)):
            embed.read(source)
        assert embed.read(source, strict=False).is_empty is True

    def test_a_predicted_stream_that_inflates_to_nothing_is_refused(self, tmp_path: Path) -> None:
        """Zero bytes are a whole number of rows of every length, which checks nothing.

        The guard on the number of rows passed vacuously on an empty inflate, and the
        row buffer was allocated anyway.
        """
        source = self.with_parms(tmp_path, "empty.pdf", PNG_PARMS)
        with pytest.raises(InvalidLabelError, match="decompresses to nothing"):
            embed.read(source)
        assert embed.read(source, strict=False).is_empty is True

    def test_the_implied_row_length_is_measured_against_the_bound(self, tmp_path: Path) -> None:
        """Each parameter can be sane and their product still enormous."""
        source = self.with_parms(
            tmp_path,
            "product.pdf",
            Dictionary(Predictor=12, Colors=32, BitsPerComponent=16, Columns=10_000_000),
        )
        with pytest.raises(InvalidLabelError, match="describing rows of"):
            embed.read(source)

    @pytest.mark.slow
    @pytest.mark.skipif(sys.platform.startswith("win"), reason="getrusage is POSIX")
    def test_refusing_costs_no_more_than_reading_a_drawing(
        self, tmp_path: Path, reader_baseline_rss: int
    ) -> None:
        """Measured, in a fresh interpreter: the assertion the error message cannot make.

        A refusal issued *after* the allocation reads exactly like a refusal issued
        before it, which is why the original defect survived a reviewer: the reader said
        no, and had already spent two gibibytes saying it.
        """
        source = self.with_parms(
            tmp_path, "absurd-columns.pdf", Dictionary(Predictor=12, Columns=2_000_000_000)
        )
        assert source.stat().st_size < 4096
        outcome, peak = peak_rss_reading(tmp_path, source, max_label_bytes=PROBE_LIMIT)
        spent = peak - reader_baseline_rss
        assert outcome == "InvalidLabelError", (
            f"reading a document with an absurd /Columns ended in {outcome!r}; a "
            "MemoryError is not a PlanLabelError, so it reaches a caller as a traceback "
            "and never as the absence section 4.3 (2) promises"
        )
        assert spent < RSS_ALLOWANCE, (
            f"refusing a {source.stat().st_size}-byte document cost "
            f"{spent / 1024**2:.1f} MB more than reading a drawing; the parameters are "
            "being multiplied and allocated before they are checked"
        )


class TestUndoingAPredictorIsBounded:
    """A bound on bytes is not a bound on time, and section 4.3 (7) asks for both.

    Undoing a predictor was a Python loop over every byte, with a function call per byte
    for Paeth: about 2.8 s for sixteen mebibytes, and the document chooses how many
    labels a reader opens. Three of the five PNG filters and the TIFF one are array
    arithmetic and are now numpy; the two that are not carry a smaller cap instead.
    """

    def test_the_sequential_cap_is_far_below_the_byte_cap(self) -> None:
        """The two caps exist because the two costs are different."""
        assert embed._MAX_SEQUENTIAL_PREDICTED_BYTES < embed._MAX_LABEL_BYTES

    @pytest.mark.slow
    @pytest.mark.parametrize("tag", [0, 1, 2])
    def test_a_full_sized_label_is_unpredicted_in_well_under_a_second(
        self, tmp_path: Path, tag: int
    ) -> None:
        """None, Sub and Up are array arithmetic, and are measured as such.

        Before they were vectorised, Sub and Up each took over a second here and this
        assertion failed on both.
        """
        source = write_bytes(tmp_path / f"big-{tag}.pdf", predicted_zeros(tag, megabytes=15))
        started = time.perf_counter()
        with pytest.raises(InvalidLabelError, match="not readable as UTF-8 JSON"):
            embed.read(source)
        elapsed = time.perf_counter() - started
        assert elapsed < PREDICTOR_TIME_BUDGET, (
            f"undoing a 15 MiB PNG predictor of type {tag} took {elapsed:.2f} s, over the "
            f"{PREDICTOR_TIME_BUDGET} s budget; the bound on bytes is holding and the "
            "bound on time is not"
        )

    @pytest.mark.parametrize("tag", [3, 4])
    def test_average_and_paeth_are_capped_where_the_other_three_are_not(
        self, tmp_path: Path, tag: int
    ) -> None:
        """Each reconstructed byte is an input to the next, so there is no array form."""
        source = write_bytes(tmp_path / f"seq-{tag}.pdf", predicted_zeros(tag, megabytes=4))
        with pytest.raises(InvalidLabelError, match="one byte at a time"):
            embed.read(source)
        assert embed.read(source, strict=False).is_empty is True

    @pytest.mark.parametrize("tag", [0, 1, 2, 3, 4])
    def test_a_label_under_a_multi_component_predictor_still_round_trips(
        self, tmp_path: Path, labels: list[PageLabel], tag: int
    ) -> None:
        """Vectorising by lane is where a rewrite goes wrong quietly.

        ``/Colors 3`` puts three independent running sums in one row, interleaved. A
        cumulative sum taken over the row rather than over its lanes decodes the first
        three bytes correctly and nothing after them.
        """
        colors, columns = 3, 5
        width = colors * columns
        payload = canonical_bytes(labels[0])
        padded = payload + b" " * (-len(payload) % width)
        stored = zlib.compress(fx.png_encode(padded, columns=width, tag=tag, step=colors), 9)
        source = write_bytes(
            tmp_path / f"lanes-{tag}.pdf",
            fx.build_filtered_label(
                stored,
                filters=Name.FlateDecode,
                decode_parms=Dictionary(
                    Predictor=15, Colors=colors, BitsPerComponent=8, Columns=columns
                ),
            ),
        )
        assert canonical_bytes(embed.read(source).pages[0]) == payload

    def test_a_tiff_predictor_over_several_components_round_trips_too(
        self, tmp_path: Path, labels: list[PageLabel]
    ) -> None:
        """The TIFF predictor has the same lanes, and no rows depending on each other."""
        colors, columns = 3, 5
        width = colors * columns
        payload = canonical_bytes(labels[0])
        padded = payload + b" " * (-len(payload) % width)
        differenced = bytearray(padded)
        for at in range(len(padded) - 1, -1, -1):
            if at % width >= colors:
                differenced[at] = (padded[at] - padded[at - colors]) & 0xFF
        source = write_bytes(
            tmp_path / "tiff-lanes.pdf",
            fx.build_filtered_label(
                zlib.compress(bytes(differenced), 9),
                filters=Name.FlateDecode,
                decode_parms=Dictionary(
                    Predictor=2, Colors=colors, BitsPerComponent=8, Columns=columns
                ),
            ),
        )
        assert canonical_bytes(embed.read(source).pages[0]) == payload


