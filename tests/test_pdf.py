# A structural pre-check of the embedded-file rules
# ---------------------------------------------------------------------------
def _association_problems(pdf: Pdf) -> tuple[list[str], set[tuple[int, int]]]:
    """Inspect every ``/AF`` array in a document.

    Args:
        pdf: An open document.

    Returns:
        The problems found, and the object identity of every file specification that
        some ``/AF`` array references.
    """
    problems: list[str] = []
    associated: set[tuple[int, int]] = set()
    owners: list[Object] = [pdf.Root, *(page.obj for page in pdf.pages)]
    for owner in owners:
        entries = owner.get(Name.AF)
        if entries is None:
            continue
        if not isinstance(entries, Array):
            problems.append(f"an /AF entry is not an array: {entries!r}")
            continue
        if len(entries) == 0:
            problems.append("an empty /AF array was left behind")
        for item in entries:
            entry = cast("Object | None", item)
            if entry is None:
                problems.append("an /AF array holds a reference to a deleted object")
            else:
                associated.add(entry.objgen)
    return problems, associated


def _filespec_problems(name: str, spec: Object) -> list[str]:
    """Check one file specification against the rules PDF/A imposes on it.

    Args:
        name: The name-tree key the specification is registered under.
        spec: The ``/Filespec`` dictionary.

    Returns:
        One message per problem, empty when it is sound.
    """
    problems: list[str] = []
    relationship = spec.get(Name.AFRelationship)
    if relationship is None:
        problems.append(f"{name!r} has no /AFRelationship")
    elif str(relationship) not in AF_RELATIONSHIPS:
        problems.append(f"{name!r} has a non-standard /AFRelationship {relationship!s}")
    if Name.UF not in spec:
        problems.append(f"{name!r} has no /UF")

    stream = spec[Name.EF][Name.F]
    if Name.Subtype not in stream.stream_dict:
        problems.append(f"{name!r}'s embedded stream has no MIME /Subtype")
    params = stream.stream_dict.get(Name.Params)
    if params is None:
        problems.append(f"{name!r}'s embedded stream has no /Params")
        return problems
    if Name.ModDate not in params:
        problems.append(f"{name!r}'s /Params has no /ModDate")
    data = bytes(stream.read_bytes())
    if int(params.get(Name.Size, -1)) != len(data):
        problems.append(
            f"{name!r}'s /Params /Size is {params.get(Name.Size)!s} "
            f"but the file is {len(data)} bytes"
        )
    checksum = params.get(Name.CheckSum)
    if checksum is None:
        problems.append(f"{name!r}'s /Params has no /CheckSum")
    elif bytes(checksum) != hashlib.md5(data).digest():  # noqa: S324 - the format says MD5
        problems.append(f"{name!r}'s /Params /CheckSum is not the MD5 of the file")
    return problems


def associated_file_problems(pdf: Pdf) -> list[str]:
    """Check the embedded-file rules a PDF/A validator would check.

    This is a pure-Python structural pre-check, not a substitute for veraPDF. It exists
    because veraPDF is absent from nearly every machine, and because these are the rules
    the carrier is actually at risk of breaking: a file in the name tree that no ``/AF``
    array references (which PDF/A-4 forbids), a file in an ``/AF`` array that the name
    tree does not list (which makes it invisible to pdf.js, to pikepdf's own mapping and
    to Acrobat's pane), a missing or vendor-specific ``/AFRelationship``, a missing MIME
    ``/Subtype``, and ``/Params`` whose ``/Size`` or ``/CheckSum`` no longer describes
    the data.

    Args:
        pdf: An open document.

    Returns:
        One message per problem, empty when the document is sound.
    """
    problems, associated = _association_problems(pdf)
    in_tree: set[tuple[int, int]] = set()
    for name in pdf.attachments:
        spec = pdf.attachments[name].obj
        in_tree.add(spec.objgen)
        if spec.objgen not in associated:
            problems.append(f"name-tree entry {name!r} is not referenced from any /AF array")
        problems.extend(_filespec_problems(name, spec))
    problems.extend(
        f"the file specification {objgen} is associated but not in the name tree"
        for objgen in sorted(associated - in_tree)
    )
    return problems


