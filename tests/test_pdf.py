def declarations_bag(path: Path) -> bytes:
    """Return the contents of a document's one ``pdfd:declarations`` property.

    Args:
        path: The document whose XMP packet to read.

    Returns:
        The bytes between the opening and closing ``pdfd:declarations`` tags.

    Raises:
        AssertionError: If the packet does not hold exactly one such property. Two
            properties of one name on one ``rdf:about`` subject is not valid XMP, and a
            reader taking the first would not see the second producer's claim at all.
    """
    packet = xmp_packet(path)
    assert packet is not None, f"{path} carries no XMP packet"
    opened = packet.count(b"<pdfd:declarations>")
    closed = packet.count(b"</pdfd:declarations>")
    assert (opened, closed) == (1, 1), (
        f"the packet carries {opened} pdfd:declarations propert(ies); a PDF Declaration "
        "is one property holding one rdf:Bag, and a second producer's claim joins that "
        "Bag rather than opening a rival property on the same rdf:about subject"
    )
    start = packet.index(b"<pdfd:declarations>") + len(b"<pdfd:declarations>")
    return packet[start : packet.index(b"</pdfd:declarations>")]


class TestTheDeclarationComposes:
    """Our claim joins another producer's Bag, and leaves it exactly as it found it."""

    def test_our_claim_joins_the_existing_bag_and_leaves_again(
        self, drawing_set: Path, labelled: Path, stripped: Path
    ) -> None:
        """One property, two members, and a byte-identical packet after stripping.

        The fixture already carries a PDF Declaration naming another specification.
        Adding a second ``pdfd:declarations`` property beside it -- which is what a
        writer that always splices a whole ``rdf:Description`` does -- makes the packet
        invalid XMP, and a reader that took the first Bag would never see PlanLabel's
        claim at all.
        """
        bag = declarations_bag(labelled)
        assert bag.count(b"<rdf:li") == 2, f"expected two declarations in one Bag: {bag!r}"
        assert FOREIGN_DECLARATION in bag
        assert f"<pdfd:conformsTo>{SPEC_URI}</pdfd:conformsTo>".encode() in bag

        after = xmp_packet(stripped)
        assert after == xmp_packet(drawing_set)
        assert after == fx.XMP_PACKET

    def test_the_spliced_member_declares_its_own_namespace(self, labelled: Path) -> None:
        """A Bag written with some other prefix must not leave ``pdfd:`` unbound.

        The member is spliced into an element this module did not write, so it cannot
        assume which prefix that element bound the PDF Declarations namespace to.
        """
        bag = declarations_bag(labelled)
        ours = bag[: bag.index(SPEC_URI.encode())].rsplit(b"<rdf:li", 1)[-1]
        assert embed.NS_PDFD.encode() in ours

    def test_a_document_with_no_declaration_at_all_gets_the_whole_property(
        self, tmp_path: Path
    ) -> None:
        """With no Bag to join, the property is written in full, once."""
        source = write_bytes(tmp_path / "bare.pdf", fx.build_bare())
        target = tmp_path / "bare-labelled.pdf"
        page_labels = [fx.page_label(page_index=0, width_mm=210.0, height_mm=297.0)]
        label(source, target, page_labels, None)
        bag = declarations_bag(target)
        assert bag.count(b"<rdf:li") == 1
        assert SPEC_URI.encode() in bag

    def test_an_empty_self_closing_bag_is_joined_rather_than_duplicated(
        self, tmp_path: Path
    ) -> None:
        """``<rdf:Bag/>`` is an array. It has no closing tag, and it is still an array.

        A writer that reads "no closing tag" as "no array" writes a second
        ``pdfd:declarations`` property beside the first, which is the invalid XMP this
        whole class exists to prevent -- in the one shape where the array is there and
        the splice point is not.
        """
        source = write_bytes(
            tmp_path / "self-closing.pdf",
            fx.build_with_xmp(fx.SELF_CLOSING_DECLARATIONS_PACKET),
        )
        target = tmp_path / "self-closing-labelled.pdf"
        page_labels = [fx.page_label(page_index=0, width_mm=210.0, height_mm=297.0)]
        label(source, target, page_labels, None)
        bag = declarations_bag(target)
        assert bag.count(b"<rdf:li") == 1
        assert SPEC_URI.encode() in bag

        stripped = tmp_path / "self-closing-stripped.pdf"
        embed.strip(target, stripped)
        assert xmp_packet(stripped) == fx.SELF_CLOSING_DECLARATIONS_PACKET

    def test_a_declarations_property_that_is_not_an_array_is_refused(self, tmp_path: Path) -> None:
        """A declarations property that is not an array is refused, not worked around.

        Section 6.3.3 makes the declarations an ``rdf:Bag``. A packet where it is not
        one is malformed before PlanLabel arrives, and repairing another producer's
        metadata is not this writer's business -- nor is writing a second property
        beside it, which is what a writer that treats "no array" as "no declarations"
        would do.
        """
        packet = fx.SELF_CLOSING_DECLARATIONS_PACKET.replace(
            b"<pdfd:declarations><rdf:Bag /></pdfd:declarations>",
            b"<pdfd:declarations />",
        )
        source = write_bytes(tmp_path / "not-an-array.pdf", fx.build_with_xmp(packet))
        page_labels = [fx.page_label(page_index=0, width_mm=210.0, height_mm=297.0)]
        with pytest.raises(DeclarationError, match="self-closing declarations property"):
            label(source, tmp_path / "out.pdf", page_labels, None)

    def test_the_claim_describes_the_subject_the_packet_already_describes(
        self, tmp_path: Path
    ) -> None:
        """XMP Part 1: every ``rdf:Description`` in one packet describes one resource.

        A writer that always writes ``rdf:about=""`` adds a second subject to a packet
        that names its own, and a reader of the named subject never sees the claim.
        """
        source = write_bytes(
            tmp_path / "named-subject.pdf", fx.build_with_xmp(fx.NAMED_SUBJECT_PACKET)
        )
        target = tmp_path / "named-subject-labelled.pdf"
        page_labels = [fx.page_label(page_index=0, width_mm=210.0, height_mm=297.0)]
        label(source, target, page_labels, None)

        packet = xmp_packet(target)
        assert packet is not None
        ours = f'rdf:about="{fx.NAMED_SUBJECT}"'.encode()
        assert packet.count(b"rdf:about=") == packet.count(ours) == 2
        assert b'rdf:about=""' not in packet
        assert declarations_bag(target).count(b"<rdf:li") == 1

        stripped = tmp_path / "named-subject-stripped.pdf"
        embed.strip(target, stripped)
        assert xmp_packet(stripped) == fx.NAMED_SUBJECT_PACKET


class TestNothingIsWrittenIntoAComment:
    """A comment and a CDATA section hold text, not markup, and no XMP reader sees them.

    Scanning the packet's bytes for a splice point without masking them first put
    PlanLabel's claim inside somebody else's comment -- and :func:`attach` then reported
    that it had written a declaration, and :func:`has_declaration` agreed, for a
    document that declared nothing at all.
    """

    @staticmethod
    def labelled_with(tmp_path: Path, name: str, packet: bytes) -> Path:
        """Label a one-page document carrying a packet of the caller's choosing.

        Args:
            tmp_path: Where to write.
            name: The filename to write the labelled copy under.
            packet: The catalog's XMP packet.

        Returns:
            The labelled document's path.
        """
        source = write_bytes(tmp_path / f"{name}-in.pdf", fx.build_with_xmp(packet))
        target = tmp_path / f"{name}.pdf"
        label(source, target, [fx.page_label(page_index=0, width_mm=210.0, height_mm=297.0)], None)
        return target

    @pytest.mark.parametrize(
        ("name", "packet"),
        [
            ("commented", fx.COMMENTED_DECLARATIONS_PACKET),
            ("cdata", fx.CDATA_DECLARATIONS_PACKET),
            ("trailing", fx.TRAILING_COMMENT_PACKET),
        ],
    )
    def test_the_claim_lands_where_a_reader_will_find_it(
        self, tmp_path: Path, name: str, packet: bytes
    ) -> None:
        """Inside the RDF element, outside every comment, and once."""
        target = self.labelled_with(tmp_path, name, packet)
        written = xmp_packet(target)
        assert written is not None
        visible = embed._visible(written)
        at = visible.find(SPEC_URI.encode())
        assert at >= 0, (
            "the claim was written where nothing can see it; the packet reads "
            f"{written.decode('utf-8', 'replace')}"
        )
        assert at < visible.rindex(b"</rdf:RDF>")

    @pytest.mark.parametrize(
        ("name", "packet"),
        [
            ("commented", fx.COMMENTED_DECLARATIONS_PACKET),
            ("cdata", fx.CDATA_DECLARATIONS_PACKET),
            ("trailing", fx.TRAILING_COMMENT_PACKET),
        ],
    )
    def test_the_packet_comes_back_exactly_as_it_went_in(
        self, tmp_path: Path, name: str, packet: bytes
    ) -> None:
        """Whatever was spliced in must come out again, comments included."""
        target = self.labelled_with(tmp_path, name, packet)
        stripped = tmp_path / f"{name}-stripped.pdf"
        report = embed.strip(target, stripped)
        assert report.declaration_removed is True
        assert report.declaration_remaining is False
        assert xmp_packet(stripped) == packet

    def test_a_commented_out_property_is_not_an_array_to_join(self, tmp_path: Path) -> None:
        """The packet declares nothing, so the whole property is written, once.

        Counted on the masked packet, because the commented-out property is still in the
        bytes: the question is how many properties a reader sees, not how many the file
        spells.
        """
        target = self.labelled_with(tmp_path, "commented", fx.COMMENTED_DECLARATIONS_PACKET)
        written = xmp_packet(target)
        assert written is not None
        visible = embed._visible(written)
        assert visible.count(b"<pdfd:declarations>") == 1
        assert visible.count(b"</pdfd:declarations>") == 1
        assert visible.count(b"<rdf:li") == 1

    def test_a_declaration_inside_a_comment_is_not_a_declaration(self, tmp_path: Path) -> None:
        """Reading has to agree with writing, or stripping cannot be honest either.

        A packet whose only ``pdfd:conformsTo`` sits in a comment claims nothing. A
        reader that says it does would let :func:`attach` skip the declaration it is
        required to write (section 6.2.1 (4)).
        """
        commented = fx.XMP_PACKET.replace(
            b"<rdf:Description xmlns:pdfd=",
            b"<!-- <rdf:Description xmlns:pdfd=",
            1,
        ).replace(b"</pdfd:declarations></rdf:Description>", b"</pdfd:declarations> --></p:x>", 1)
        source = write_bytes(tmp_path / "hidden.pdf", fx.build_with_xmp(commented))
        with pikepdf.open(source) as pdf:
            assert embed.has_declaration(pdf) is False

    def test_a_copy_of_our_own_claim_inside_a_comment_is_left_alone(self, tmp_path: Path) -> None:
        """Removing text from another producer's comment is editing their metadata."""
        member = (
            b'<rdf:li rdf:parseType="Resource" xmlns:pdfd="http://pdfa.org/declarations/">'
            b"<pdfd:conformsTo>" + SPEC_URI.encode() + b"</pdfd:conformsTo></rdf:li>"
        )
        packet = fx.XMP_PACKET.replace(
            b" </rdf:RDF>", b" <!-- once we wrote " + member + b" here --></rdf:RDF>", 1
        )
        source = write_bytes(tmp_path / "commented-claim.pdf", fx.build_with_xmp(packet))
        stripped = tmp_path / "commented-claim-stripped.pdf"
        report = embed.strip(source, stripped)
        assert report.declaration_removed is False
        assert xmp_packet(stripped) == packet

    @pytest.mark.parametrize(
        ("packet", "expected"),
        [
            (b"<a/><!--<b/>--><c/>", b"<a/>\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00<c/>"),
            (b"<a/><![CDATA[<b/>]]><c/>", b"<a/>" + bytes(16) + b"<c/>"),
            (b"<a/><!--unterminated", b"<a/>" + bytes(16)),
            (b"<a/><!DOCTYPE x><b/>", b"<a/><!DOCTYPE x><b/>"),
            (b"<a/>", b"<a/>"),
            (b"<!---->", bytes(7)),
        ],
    )
    def test_the_mask_keeps_every_offset(self, packet: bytes, expected: bytes) -> None:
        """A splice point found in the mask is applied to the packet, so they must align."""
        masked = embed._visible(packet)
        assert masked == expected
        assert len(masked) == len(packet)


