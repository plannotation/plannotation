def wait_past_a_clock_second(since: float) -> None:
    """Sleep until more than a second has passed since a moment.

    Args:
        since: A :func:`time.monotonic` reading taken before the work that is being
            waited out, so that only the remainder of the second is spent sleeping.
    """
    remaining = CLOCK_TICK - (time.monotonic() - since)
    if remaining > 0:
        time.sleep(remaining)


def run_in_fresh_interpreter(tmp_path: Path, body: str) -> bytes:
    """Run a snippet in a new interpreter and return the bytes it wrote.

    The snippet is given ``sys``, ``Path`` and the repository root on ``sys.path``, and
    writes its result to ``sys.argv[1]``. The environment is deliberately hostile to
    accidental determinism: a different hash seed and a different time zone.

    Args:
        tmp_path: A directory to put the script and its output in.
        body: The snippet's source.

    Returns:
        The bytes the snippet wrote.
    """
    root = Path(__file__).resolve().parents[1]
    script = tmp_path / "rebuild.py"
    script.write_text(
        f"import sys\nfrom pathlib import Path\nsys.path.insert(0, {str(root)!r})\n{body}",
        encoding="utf-8",
    )
    output = tmp_path / "rebuilt.bin"
    environment = dict(os.environ)
    environment["PYTHONHASHSEED"] = "424242"
    environment["TZ"] = "Pacific/Kiritimati"
    finished = subprocess.run(  # noqa: S603 - a script just written here, run with no shell
        [sys.executable, str(script), str(output)],
        capture_output=True,
        text=True,
        timeout=VERAPDF_TIMEOUT,
        env=environment,
        check=False,
    )
    assert finished.returncode == 0, finished.stderr
    return output.read_bytes()


class TestDeterminism:
    """Two runs over the same inputs must produce the same file."""

    def test_two_runs_in_one_process_agree(
        self, drawing_set: Path, tmp_path: Path, labels: list[PageLabel], index: LabelIndex
    ) -> None:
        """The obvious half of the claim."""
        first = tmp_path / "first.pdf"
        second = tmp_path / "second.pdf"
        label(drawing_set, first, labels, index)
        label(drawing_set, second, labels, index)
        assert first.read_bytes() == second.read_bytes()

    @pytest.mark.slow
    def test_a_fresh_interpreter_a_second_later_agrees_too(
        self, drawing_set: Path, tmp_path: Path, labels: list[PageLabel], index: LabelIndex
    ) -> None:
        """The half that matters.

        pikepdf's default ``/ID`` is seeded from the clock at one-second granularity,
        so two runs inside the same second produce the same bytes whether or not
        anything is pinned. This one crosses a process boundary *and* a second
        boundary, with a different hash seed and a different time zone -- verified to
        fail when ``deterministic_id`` is taken out of
        :func:`planlabel.pdf.embed.save_labelled`, which the immediate comparison did
        not.
        """
        here = tmp_path / "here.pdf"
        label(drawing_set, here, labels, index)
        started = time.monotonic()
        there = run_in_fresh_interpreter(
            tmp_path,
            "from datetime import UTC, datetime\n"
            "from tests.pdf_fixtures import build_drawing_set, drawing_set_labels\n"
            "from planlabel.pdf.embed import attach, build_index\n"
            "target = Path(sys.argv[1])\n"
            "source = target.with_name('source.pdf')\n"
            "source.write_bytes(build_drawing_set())\n"
            "page_labels = drawing_set_labels()\n"
            "attach(source, page_labels, build_index(page_labels), target,\n"
            "       mod_date=datetime(2024, 1, 1, 12, 0, 0, tzinfo=UTC))\n",
        )
        wait_past_a_clock_second(started)
        again = tmp_path / "again.pdf"
        label(drawing_set, again, labels, index)
        assert hashlib.sha256(there).hexdigest() == hashlib.sha256(here.read_bytes()).hexdigest()
        assert again.read_bytes() == here.read_bytes()

    def test_the_timestamp_really_reaches_the_output(
        self, drawing_set: Path, tmp_path: Path, labels: list[PageLabel], index: LabelIndex
    ) -> None:
        """Otherwise the determinism tests would prove only that nothing ever varies."""
        first = tmp_path / "first.pdf"
        second = tmp_path / "second.pdf"
        label(drawing_set, first, labels, index)
        embed.attach(
            drawing_set,
            labels,
            index,
            second,
            mod_date=datetime(2025, 6, 1, 9, 30, 0, tzinfo=UTC),
        )
        assert first.read_bytes() != second.read_bytes()
        with pikepdf.open(second) as pdf:
            stream = pdf.attachments[INDEX_FILENAME].obj[Name.EF][Name.F]
            assert str(stream.stream_dict[Name.Params][Name.ModDate]) == "D:20250601093000Z"

    def test_writing_in_place_gives_the_same_file(
        self, drawing_set: Path, tmp_path: Path, labels: list[PageLabel], index: LabelIndex
    ) -> None:
        """Labelling a document over itself is the same operation as labelling a copy."""
        copy = write_bytes(tmp_path / "in-place.pdf", drawing_set.read_bytes())
        label(copy, copy, labels, index)
        elsewhere = tmp_path / "elsewhere.pdf"
        label(drawing_set, elsewhere, labels, index)
        assert copy.read_bytes() == elsewhere.read_bytes()


